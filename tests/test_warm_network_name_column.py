#!/usr/bin/env python3
"""BUG-560: feed_install.read_warm()'s warm-network.md fallback took the first table cell as the
name. The real file's header is `| | Name | Title | Company | Known since | |` -- an empty first
column, with each data row's first cell a bare RANK NUMBER ("1", "2", "3", ...). Every name read
this way normalized to a digit string, which never matches a real boss name, so the warm rung
silently never lit for an install relying on this fallback (contact.jsonl empty, warm-network.md
the only source) -- not inaccurate, completely dark. Fixed by reading the column the header
actually names "Name", per table (the file ships several independent tables).

All names below are invented. Red-first: every test here was written to fail against the
pre-fix `_board_names()`-based fallback and is checked against `_warm_names()`.
"""
import json
import os
import shutil
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(KIT, "scripts"))
import feed_install  # noqa: E402

REAL_SHAPE = """# Warm network — ranked warm-outreach targets

> Generated by `scripts/parse_network.py`.

## Product people — potential boss or peer (3)

| | Name | Title | Company | Known since | |
|---|---|---|---|---|---|
| 1 | Zz Alpha Fakeperson ✅ | Product Leader | Zzyzx Sprockets | 🟢 3y (2023-07-16) | ✉  |
| 2 | Zz Beta Fakeperson | Product Manager | Quorbex Labs | 🟢 3y (2023-08-04) |   |
| 3 | Zz Gamma Fakeperson | Staff PM | Wrenfield Systems | 🟢 3y (2023-07-27) |   |

## Connector people — can make an introduction (1)

| | Name | Title | Company | Known since | |
|---|---|---|---|---|---|
| 1 | Zz Delta Fakeperson | Recruiter | Halden Public Works | 🟡 2y (2024-01-02) |   |
"""

BULLET_SHAPE = """# Warm network

- **Zz Alpha Fakeperson** -- Zzyzx Sprockets
- **Zz Beta Fakeperson** -- Quorbex Labs
"""

NAME_FIRST_SHAPE = """# Warm network

| Name | Company |
|---|---|
| Zz Alpha Fakeperson | Zzyzx Sprockets |
"""


class WarmNamesColumnTests(unittest.TestCase):
    """_warm_names() directly, on invented text -- no filesystem involved."""

    def test_the_real_file_shape_reads_the_name_column_not_the_rank_number(self):
        names = feed_install._warm_names(REAL_SHAPE)
        self.assertIn("Zz Alpha Fakeperson", names)
        self.assertNotIn("1", names)
        self.assertNotIn("2", names)
        self.assertNotIn("3", names)

    def test_a_trailing_verified_or_contacted_mark_is_stripped_from_the_name(self):
        names = feed_install._warm_names(REAL_SHAPE)
        self.assertIn("Zz Alpha Fakeperson", names)
        self.assertNotIn("Zz Alpha Fakeperson ✅", names)

    def test_every_table_in_a_multi_table_file_is_read_by_its_own_header(self):
        names = feed_install._warm_names(REAL_SHAPE)
        self.assertIn("Zz Delta Fakeperson", names)

    def test_no_rank_number_or_header_word_ever_appears_as_a_name(self):
        names = feed_install._warm_names(REAL_SHAPE)
        for junk in ("1", "2", "3", "name", "Name", ""):
            self.assertNotIn(junk, names)

    def test_a_bullet_only_file_with_no_table_falls_back_to_bold_bullets(self):
        names = feed_install._warm_names(BULLET_SHAPE)
        self.assertEqual(names, ["Zz Alpha Fakeperson", "Zz Beta Fakeperson"])

    def test_a_table_whose_first_column_really_is_the_name_still_works(self):
        """A simpler hand-written warm-network.md, where Name genuinely is the first column,
        must still read correctly -- the fix locates the header, it does not special-case the
        rank-number shape as the only one."""
        names = feed_install._warm_names(NAME_FIRST_SHAPE)
        self.assertEqual(names, ["Zz Alpha Fakeperson"])

    def test_an_empty_or_missing_file_yields_no_names(self):
        self.assertEqual(feed_install._warm_names(""), [])
        self.assertEqual(feed_install._warm_names(None), [])

    def test_board_names_itself_is_unchanged_and_still_reads_the_first_cell(self):
        """_board_names() is the reader for green-board.md/discovery-board.md, where the first
        column genuinely IS the company -- this fix must not touch its own behavior."""
        board_text = "| Company | Stage |\n|---|---|\n| Zzyzx Sprockets | BANKED |\n"
        self.assertEqual(feed_install._board_names(board_text), ["Zzyzx Sprockets"])


class ReadWarmFallbackTests(unittest.TestCase):
    """read_warm() end to end, against a disposable fixture repo with ONLY warm-network.md (no
    contact.jsonl) -- the exact condition that forces the fallback this bug lived in."""

    def setUp(self):
        self.repo = tempfile.mkdtemp(prefix="warm560-")
        os.makedirs(os.path.join(self.repo, "documents"), exist_ok=True)

    def tearDown(self):
        shutil.rmtree(self.repo, ignore_errors=True)

    def _write_warm(self, text):
        with open(os.path.join(self.repo, "documents", "warm-network.md"), "w", encoding="utf-8") as f:
            f.write(text)

    def test_read_warm_names_key_on_the_real_person_never_a_rank_number(self):
        self._write_warm(REAL_SHAPE)
        warm = feed_install.read_warm(self.repo)
        normalized = {warm["normalize"]("Zz Alpha Fakeperson"), warm["normalize"]("Zz Beta Fakeperson"),
                     warm["normalize"]("Zz Gamma Fakeperson"), warm["normalize"]("Zz Delta Fakeperson")}
        self.assertTrue(normalized <= set(warm["names"]), warm["names"])
        for n in ("1", "2", "3"):
            self.assertNotIn(warm["normalize"](n), warm["names"])

    def test_read_warm_is_empty_on_a_file_with_no_name_column_or_bullets(self):
        self._write_warm("# Warm network\n\n| Rank | Title |\n|---|---|\n| 1 | VP |\n")
        warm = feed_install.read_warm(self.repo)
        self.assertEqual(warm["names"], {})


class AnnotateWarmRungTests(unittest.TestCase):
    """feed_install.annotate(): the added card's warm rung, the consumer the bug actually breaks
    end to end -- a boss who IS in the fallback-sourced warm network must light up "warm"."""

    def setUp(self):
        self.repo = tempfile.mkdtemp(prefix="warm560-annotate-")
        os.makedirs(os.path.join(self.repo, "documents"), exist_ok=True)

    def tearDown(self):
        shutil.rmtree(self.repo, ignore_errors=True)

    def test_a_card_whose_boss_matches_the_fallback_warm_network_gets_the_warm_rung_once_a_tier_sanctions_it(self):
        """BUG-600: the name match alone no longer lights "warm"; the closeness store has to sanction a warm ask. The control writes that tier."""
        with open(os.path.join(self.repo, "documents", "warm-network.md"), "w", encoding="utf-8") as f:
            f.write(REAL_SHAPE)
        warm = feed_install.read_warm(self.repo)
        self.assertIn("zz alpha fakeperson", warm["names"])      # the fallback still RECOGNIZES the name
        card = {"slug": "zzyzx-sprockets", "company": "Zzyzx Sprockets", "boss": {"name": "Zz Alpha Fakeperson"}}
        feed_install.annotate([card], [], warm, [])
        self.assertIsNone(card["rung"])
        with open(os.path.join(self.repo, "documents", "contact-closeness.json"), "w", encoding="utf-8") as f:
            json.dump({"contacts": {"Zz Alpha Fakeperson": {"closeness": "know-well"}}}, f)
        warm = feed_install.read_warm(self.repo)
        card = {"slug": "zzyzx-sprockets", "company": "Zzyzx Sprockets", "boss": {"name": "Zz Alpha Fakeperson"}}
        feed_install.annotate([card], [], warm, [])
        self.assertEqual(card["rung"], "warm")

    def test_a_boss_not_in_the_network_is_not_warm(self):
        with open(os.path.join(self.repo, "documents", "warm-network.md"), "w", encoding="utf-8") as f:
            f.write(REAL_SHAPE)
        warm = feed_install.read_warm(self.repo)
        card = {"slug": "quorbex-labs", "company": "Quorbex Labs", "boss": {"name": "Someone Unlisted"}}
        feed_install.annotate([card], [], warm, [])
        self.assertIsNone(card["rung"])


if __name__ == "__main__":
    unittest.main()
