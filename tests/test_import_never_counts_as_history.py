#!/usr/bin/env python3
"""test_import_never_counts_as_history.py -- slice A commit 3 (BUG-601), test (b3).

local_gates.dedup_sources_nonempty used to return True as soon as feed_install.read_warm(repo) had ANY name, so the moment a fresh install
imported a LinkedIn export (or kept a warm-network.md, or a contact-closeness.json) every card's dedup gate read pass with counts True and
Decide opened on a history that holds no touch at all: an empty check that passes. Now dedup counts only what prior_contact can find: the send log,
the stores in check_dup.SEND_GATE_STORES (minus the blocked list, which gate_dedup ignores), and contact rows that record a touch.
A contact row from an export alone never counts. Dedup wording: "not asked yet, counts false". Names are obviously fake.
"""
import json
import os
import _roots
import shutil
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(os.path.dirname(HERE), "scripts")
sys.path.insert(0, SCRIPTS)
import check_dup  # noqa: E402
import local_gates as lg  # noqa: E402

COMPANY = "Zzqco Fake Works"
SLUG = "zzqco-fake-works"


def _clean(_company):
    return ("CLEAN", "")


class Base(unittest.TestCase):
    def setUp(self):
        self.d = tempfile.mkdtemp(prefix="nohistory_", dir=os.environ.get("TMPDIR"))
        self.addCleanup(shutil.rmtree, self.d, True)
        os.makedirs(os.path.join(self.d, "documents", "state"))

    def write(self, rel, text):
        p = os.path.join(self.d, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(text)

    def import_only(self):
        """What a fresh LinkedIn import leaves: contact rows (no touch), a generated warm-network.md, a closeness store."""
        rows = [{"kind": "contact", "key": "zzqana-testperson", "payload": {"name": "Zzqana Testperson", "company": COMPANY}},
                {"kind": "contact", "key": "zzqbo-otherperson", "payload": {"name": "Zzqbo Otherperson", "company": "Zzqdo Other Works"}}]
        self.write("documents/state/contact.jsonl", "".join(json.dumps(r) + "\n" for r in rows))
        self.write("documents/warm-network.md", "> Generated by parse_network\n\n| Rank | Name | Company |\n|---|---|---|\n| 1 | Zzqana Testperson | %s |\n" % COMPANY)
        self.write("documents/contact-closeness.json", json.dumps({"contacts": {"Zzqana Testperson": {"closeness": "know-well"}}}))


class ImportOnlyIsNotHistory(Base):
    def test_an_install_whose_only_history_is_the_imported_export_counts_nothing(self):
        self.import_only()
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_the_warm_network_file_alone_counts_nothing(self):
        self.write("documents/warm-network.md", "| Name | Company |\n|---|---|\n| Zzqana Testperson | %s |\n" % COMPANY)
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_the_closeness_store_alone_counts_nothing(self):
        self.write("documents/contact-closeness.json", json.dumps({"contacts": {"Zzqana Testperson": {"closeness": "know-well"}}}))
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_header_only_history_files_count_nothing(self):
        self.write("outreach_log.md", "# Outreach Log\n")
        self.write("job_search_tracker.csv", "date,company,status\n")
        self.write("documents/correspondence-log.md", "# Correspondence\n")
        self.write("documents/blocked-employers-list.md", "# Blocked\n\n- Zzqeo Blocked Works (declined)\n")
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_decide_stays_gray_on_an_import_only_install(self):
        """End to end through run(): every dedup gate reads 'not asked yet', counts false."""
        self.import_only()
        self.write("documents/state/%s-card-2026-10-08.md" % SLUG, "# %s · applied-ai · panel 80/80/80\n\nFixture.\n" % COMPANY)
        lg.run(self.d, blocked_check=_clean, prior_check=check_dup.prior_contact, today="2026-10-08")
        with open(os.path.join(self.d, "documents", "state", "local-gates.json"), encoding="utf-8") as fh:
            entry = json.load(fh)[SLUG]
        self.assertFalse(entry["dedup"]["counts"], entry["dedup"])
        self.assertEqual(entry["dedup"]["state"], "unresolved")
        self.assertEqual(entry["dedup"]["why"], lg.NOT_ASKED_YET)


SEED_OUTREACH = ("# Outreach Log\n\nOne block per send.\n\n\u26d4 NO RUNG ARMS A FOLLOW-UP. Every send records FOLLOWUP-DUE: none, warm included. The token must be PRESENT.\n\n"
                 "Chasing silence is retired on purpose. A REPLY, a THANK-YOU and a new contact at the same company are all still fair game.\n")


class WhatCountsAsARecord(Base):
    """R245 MUST: the dedup gate must count what check_dup.search_file can find. A thread header, a quoted reply, an undated heading all count; a title, a
    table header and a fresh install's seed text do not."""

    def test_a_blockquote_only_correspondence_log_counts_and_that_company_reads_warn(self):
        self.write("documents/correspondence-log.md", "# Correspondence Log\n\n## %s thread\n\n> %s replied: happy to talk.\n" % (COMPANY, COMPANY))
        self.assertTrue(lg.dedup_sources_nonempty(self.d))
        self.write("documents/state/%s-card-2026-10-08.md" % SLUG, "# %s · applied-ai · panel 80/80/80\n\nFixture.\n" % COMPANY)
        old = check_dup.REPO
        check_dup.REPO = self.d
        _roots.patch_roots(self, self.d)
        self.addCleanup(setattr, check_dup, "REPO", old)
        lg.run(self.d, blocked_check=_clean, prior_check=check_dup.prior_contact, today="2026-10-08")
        with open(os.path.join(self.d, "documents", "state", "local-gates.json"), encoding="utf-8") as fh:
            entry = json.load(fh)[SLUG]
        self.assertTrue(entry["dedup"]["counts"], entry["dedup"])
        self.assertIn(entry["dedup"]["state"], ("warn", "fail"), entry["dedup"])

    def test_an_undated_heading_plus_a_quote_counts(self):
        self.write("outreach_log.md", "# Outreach Log\n\n## Zzqco thread, no date\n\n> a quoted line\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_a_heading_alone_counts(self):
        self.write("documents/correspondence-log.md", "# Correspondence Log\n\n### Zzqco Fake Works\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_an_h1_title_alone_counts_nothing(self):
        for rel in ("outreach_log.md", "documents/correspondence-log.md"):
            self.write(rel, "# A title\n")
            self.assertFalse(lg.dedup_sources_nonempty(self.d), rel)

    def test_a_table_header_and_separator_count_nothing_but_a_body_row_does(self):
        self.write("outreach_log.md", "| Date | Company |\n|---|---|\n")
        self.assertFalse(lg.dedup_sources_nonempty(self.d))
        self.write("outreach_log.md", "| Date | Company |\n|---|---|\n| 2026-09-01 | Zzqco Fake Works |\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_an_html_comment_counts_nothing(self):
        self.write("outreach_log.md", "# Outreach Log\n<!-- a note to the owner -->\n")
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_the_text_a_fresh_install_seeds_counts_nothing(self):
        """install.sh seeds outreach_log.md with prose under its title. A fresh install must not read as having a history."""
        self.write("outreach_log.md", SEED_OUTREACH)
        self.write("documents/correspondence-log.md", "# Correspondence Log\n\nVerbatim record of every message sent and received.\n")
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_a_single_h1_heading_that_carries_a_date_counts(self):
        """R245b: his real log has one. A title with no date still counts nothing (test_an_h1_title_alone_counts_nothing)."""
        self.write("outreach_log.md", "# Outreach log, last updated 2026-09-01\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))
        self.write("outreach_log.md", "# Outreach log, last updated Sep 1, 2026\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_dates_written_with_a_month_name_count(self):
        for line in ("Sent a note to Zzqco Fake Works on Sep 1, 2026.", "Sent a note on September 1, 2026.", "Sent a note on 1 Sep 2026.",
                     "Sent a note on 1 September 2026.", "Sent a note on Sept. 1, 2026."):
            self.write("outreach_log.md", "# Outreach Log\n\n%s\n" % line)
            self.assertTrue(lg.dedup_sources_nonempty(self.d), line)

    def test_a_month_name_without_a_year_or_a_day_is_not_a_date(self):
        for line in ("May the best note win.", "Next steps in March.", "One block per send in the sept column."):
            self.write("outreach_log.md", "# Outreach Log\n\n%s\n" % line)
            self.assertFalse(lg.dedup_sources_nonempty(self.d), line)

    def test_a_dated_prose_line_counts(self):
        self.write("outreach_log.md", "# Outreach Log\n\nSent a note to Zzqco Fake Works on 2026-09-01.\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))


class TheControlsCount(Base):
    def test_one_send_log_row_makes_the_gate_count(self):
        self.import_only()
        self.write("documents/send-log.jsonl", json.dumps({"company": "Zzqdo Other Works", "status": "sent"}) + "\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_a_tracker_row_alone_counts(self):
        self.import_only()
        self.write("job_search_tracker.csv", "date,company,status\n2026-09-01,%s,applied\n" % COMPANY)
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_an_outreach_log_or_correspondence_row_counts(self):
        self.write("outreach_log.md", "# Outreach Log\n\n- 2026-09-01 sent to Zzqana Testperson at %s\n" % COMPANY)
        self.assertTrue(lg.dedup_sources_nonempty(self.d))
        os.remove(os.path.join(self.d, "outreach_log.md"))
        self.write("documents/correspondence-log.md", "# Correspondence\n\n## 2026-09-01 thread with Zzqana Testperson\n")
        self.assertTrue(lg.dedup_sources_nonempty(self.d))

    def test_a_contact_row_that_records_a_touch_counts(self):
        for field in ("touch", "last_contact"):
            row = {"kind": "contact", "key": "zzqana-testperson", "payload": {"name": "Zzqana Testperson", field: "2026-09-01"}}
            self.write("documents/state/contact.jsonl", json.dumps(row) + "\n")
            self.assertTrue(lg.dedup_sources_nonempty(self.d), field)

    def test_the_blocked_list_never_counts_as_history(self):
        self.write("documents/blocked-employers-list.md", "# Blocked\n\n- Zzqeo Blocked Works (declined, culture)\n")
        self.assertFalse(lg.dedup_sources_nonempty(self.d))

    def test_a_tracker_row_makes_that_companys_gate_read_warn(self):
        """The second control (R240c): a tracker row alone for a company makes THAT company's dedup gate count and read warn/fail, via the real prior_contact."""
        self.import_only()
        self.write("job_search_tracker.csv", "date,company,status\n2026-09-01,%s,applied\n" % COMPANY)
        self.write("documents/state/%s-card-2026-10-08.md" % SLUG, "# %s · applied-ai · panel 80/80/80\n\nFixture.\n" % COMPANY)
        old = check_dup.REPO
        check_dup.REPO = self.d
        _roots.patch_roots(self, self.d)
        self.addCleanup(setattr, check_dup, "REPO", old)
        lg.run(self.d, blocked_check=_clean, prior_check=check_dup.prior_contact, today="2026-10-08")
        with open(os.path.join(self.d, "documents", "state", "local-gates.json"), encoding="utf-8") as fh:
            entry = json.load(fh)[SLUG]
        self.assertTrue(entry["dedup"]["counts"], entry["dedup"])
        self.assertIn(entry["dedup"]["state"], ("warn", "fail"), entry["dedup"])


class TheListIsImportedNotCopied(unittest.TestCase):
    def test_the_stores_come_from_check_dup(self):
        with open(os.path.join(SCRIPTS, "local_gates.py"), encoding="utf-8") as fh:
            src = fh.read()
        self.assertIn("SEND_GATE_STORES", src)
        for hand_copied in ('"job_search_tracker.csv"', '"outreach_log.md"', '"correspondence-log.md"'):
            self.assertNotIn(hand_copied, src, "a store name is hand-copied into local_gates.py: %s" % hand_copied)


if __name__ == "__main__":
    unittest.main()
