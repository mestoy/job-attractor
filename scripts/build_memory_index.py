# ── store path ────────────────────────────────────────────────────────────────────────────────────
def store_dir():
    env = os.environ.get("JOBSEARCH_MEMORY_DIR")
    if env:
        return env
    for c in STORE_CANDIDATES:
        if os.path.isdir(c):
            return c
