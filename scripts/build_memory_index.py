# ── frontmatter ───────────────────────────────────────────────────────────────────────────────────
FM_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def _unquote(v):
    v = v.strip()
    if v.startswith('"'):
        try:
            return json.loads(v)
        except ValueError:
            return v.strip('"')
    return v


def _quote(v):
    if isinstance(v, int):
        return str(v)
    return json.dumps(v, ensure_ascii=False)


def read_meta(text):
    """Return (frontmatter_text or None, top-level dict, metadata dict)."""
    m = FM_RE.match(text)
    if not m:
        return None, {}, {}
    top, meta, in_meta = {}, {}, False
    for line in m.group(1).split("\n"):
        if re.match(r"metadata:\s*$", line):
            in_meta = True
            continue
        if in_meta and re.match(r"\s+\S", line):
            k, _, v = line.strip().partition(":")
            meta[k.strip()] = _unquote(v)
            continue
        in_meta = False
        k, _, v = line.partition(":")
        if _:
            top[k.strip()] = _unquote(v)
    return m.group(1), top, meta


def write_meta(path, updates):
    """Set the managed keys in `updates` under metadata:, preserving everything else and the mtime."""
    st = os.stat(path)
    text = open(path, encoding="utf-8").read()
    m = FM_RE.match(text)
    if not m:
        name = os.path.basename(path)[:-3]
        fm = f"---\nname: {name}\nmetadata:\n" + "".join(f"  {k}: {_quote(v)}\n" for k, v in updates.items()) + "---\n"
        new = fm + text
    else:
        lines = m.group(1).split("\n")
        out, in_meta, seen_meta, done = [], False, False, False

        def emit_managed():
            return [f"  {k}: {_quote(v)}" for k, v in updates.items()]

        for line in lines:
            if re.match(r"metadata:\s*$", line):
                in_meta, seen_meta = True, True
                out.append(line)
                continue
            if in_meta and re.match(r"\s+\S", line):
                k = line.strip().partition(":")[0].strip()
                if k in updates:
                    continue               # rewritten below, at the end of the block
                out.append(line)
                continue
            if in_meta and not done:
                out.extend(emit_managed()); done = True
            in_meta = False
            out.append(line)
        if in_meta and not done:
            out.extend(emit_managed()); done = True
        if not seen_meta:
            out.append("metadata:"); out.extend(emit_managed())
        new = "---\n" + "\n".join(out) + "\n---\n" + text[m.end():]
    if new != text:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new)
        os.utime(path, (st.st_atime, st.st_mtime))   # the build reads age; a rewrite is not an edit


# ── model ─────────────────────────────────────────────────────────────────────────────────────────
class Entry:
    __slots__ = ("slug", "path", "tier", "label", "section", "row", "mark", "order", "user", "modified",
                 "desc", "lane", "lane_only")

    def __init__(self, path, top, meta):
        self.path = path
        self.slug = os.path.basename(path)
        self.desc = str(top.get("description", "")).strip()
        self.user = str(meta.get("type", "")).strip() == "user"
        self.label = str(meta.get("label", "")).strip()
        self.section = str(meta.get("section", "")).strip()
        self.row = str(meta.get("row", "")).strip()
        self.mark = str(meta.get("mark", "")).strip()
        try:
            self.order = int(meta.get("order", 10**9))
        except ValueError:
            self.order = 10**9
        t = str(meta.get("tier", "")).strip()
        self.tier = 1 if t == "1" else 2
        if self.user or self.marked():
            self.tier = 1
        mod = str(meta.get("modified", "")).strip()
        self.modified = None
        if mod:
            try:
                self.modified = datetime.fromisoformat(mod.replace("Z", "+00:00")).timestamp()
            except ValueError:
                self.modified = None
        if self.modified is None:
            self.modified = os.stat(path).st_mtime
        lane = str(meta.get("lane", "")).strip()
        self.lane = lane if lane in LANE_VALUES else ALL_LANE
        # ⭐ (unpinned) lives ONLY in its lane digest(s), never tier 1 or tier 2 (2026-09-13 shape
        # plan): the marked set that fills tier 1 to its cap is now `type: user` + ⛔ only.
        self.lane_only = self.star() and not (self.user or self.marked())

    def marked(self):
        return "⛔" in self.mark or "⛔" in self.row

    def star(self):
        return "⭐" in self.mark or "⭐" in self.row

    def pinned(self):
        return self.user or self.marked()

    def pointer(self):
        sep = " " if self.mark and re.search(r"[A-Za-z0-9:]$", self.mark) else ""   # "superseded: [x]"
        return f"{self.mark}{sep}[{self.label}]({self.slug})"


def load_entries(mem):
    entries, orphans = [], []
    for path in sorted(glob.glob(os.path.join(mem, "*.md"))):
        slug = os.path.basename(path)
        if slug in (INDEX_T1, INDEX_T2):
            continue
        text = open(path, encoding="utf-8", errors="ignore").read()
        fm, top, meta = read_meta(text)
        if fm is None:
            orphans.append(slug)           # no frontmatter: nothing to place it by
            continue
        e = Entry(path, top, meta)
        if not e.label:                    # a new file: default tier 2, description as the label
            e.label = (e.desc or slug[:-3])[:60]
            if not e.section:
                e.section = UNFILED
            e.tier = 1 if e.pinned() else 2
        if not e.section:
            e.section = UNFILED if e.tier == 2 else TOP
        entries.append(e)
    return entries, orphans


# ── rendering ─────────────────────────────────────────────────────────────────────────────────────
def _rows(entries):
    """Group entries into (section, row_key) → sorted list; row_key keeps headless lines apart."""
    rows = {}
    for e in sorted(entries, key=lambda x: (x.order, x.slug)):
        key = (e.section, e.row)
        rows.setdefault(key, []).append(e)
    return rows


def _render_row(head, items):
    body = " ·".join(x.pointer() for x in items)
    return f"- {head} {body}" if head else f"- {body}"


def _section_order(names, fixed):
    known = [s for s in fixed if s in names]
    extra = sorted(s for s in names if s not in fixed)
    return known + extra


def render(entries, tier):
    tier_entries = [e for e in entries if e.tier == tier and not e.lane_only]
    rows = _rows(tier_entries)
    sections = {}
    for (sec, row), items in rows.items():
        sections.setdefault(sec, []).append((min(x.order for x in items), row, items))
    out = [T1_HEADER if tier == 1 else T2_HEADER]
    fixed = T1_ORDER if tier == 1 else T2_ORDER + T1_ORDER
    for sec in _section_order(sections, fixed):
        body = []
        for _, row, items in sorted(sections[sec], key=lambda t: (t[0], t[1])):
            head = "" if row.startswith("~") else row
            body.append(_render_row(head, items))
        static = T2_STATIC.get(sec, {}) if tier == 2 else {}
        if tier == 1 and sec == "Search & filters":
            out.append(T1_SECTION_MAP)
        if sec == TOP:
            out.append("\n".join(body) + "\n")
        else:
            out.append(f"## {sec}\n" + "\n".join(static.get("pre", []) + body + static.get("post", [])) + "\n")
    if tier == 1 and "Search & filters" not in sections:
        out.insert(2, T1_SECTION_MAP)
    if tier == 1:
        out.insert(1, T1_LANE_MAP)
    return "\n".join(out)


def render_lane(entries, lane):
    """⭐ entries visible to `lane`: its own lane, plus every `lane: all` entry (shared everywhere)."""
    items = [e for e in entries if e.star() and (e.lane == lane or e.lane == ALL_LANE)]
    rows = _rows(items)
    sections = {}
    for (sec, row), its in rows.items():
        sections.setdefault(sec, []).append((min(x.order for x in its), row, its))
    title = lane.capitalize() if lane != ALL_LANE else "All-lane"
    out = [LANE_HEADER.format(title=title, lane=lane)]
    for sec in _section_order(sections, []):
        body = []
        for _, row, its in sorted(sections[sec], key=lambda t: (t[0], t[1])):
            head = "" if row.startswith("~") else row
            body.append(_render_row(head, its))
        if sec == TOP:
            out.append("\n".join(body) + "\n")
        else:
            out.append(f"## {sec}\n" + "\n".join(body) + "\n")
    return "\n".join(out)


def render_lanes(entries):
    return {lane: render_lane(entries, lane) for lane in LANE_VALUES}


def loaded_size(text):
    """Measure the way the harness measures (and consistency-check step 8): no frontmatter, no comments."""
    m = FM_RE.match(text)
    t = text[m.end():] if m else text
    t = re.sub(r"(?m)^[ \t]*<!--.*?-->[ \t]*\n?", "", t, flags=re.S)
    return len(t.splitlines()), len(t.encode("utf-8"))


def over_budget(text):
    lines, nbytes = loaded_size(text)
    return lines > MAX_LINES or nbytes > MAX_BYTES, lines, nbytes


# ── verification ──────────────────────────────────────────────────────────────────────────────────
POINTER_RE = re.compile(r"\]\(([A-Za-z0-9._-]+\.md)\)")


def verify_index(mem, t1, t2, orphans, lane_texts=None):
    """Orphans (file with no pointer) and dangling (pointer with no file) are red.
    A pointer in MEMORY.md, MEMORY-PLAYBOOKS.md OR any MEMORY-LANES/<lane>.md satisfies the rule."""
    links = set(POINTER_RE.findall(t1)) | set(POINTER_RE.findall(t2))
    for lt in (lane_texts or {}).values():
        links |= set(POINTER_RE.findall(lt))
    files = {os.path.basename(f) for f in glob.glob(os.path.join(mem, "*.md"))} - {INDEX_T1, INDEX_T2}
    problems = []
    orph = sorted((files - links) | set(orphans))
    dang = sorted(links - files)
    if orph:
        problems.append(f"🔴 {len(orph)} memory file(s) NOT indexed (orphan): " + ", ".join(orph[:10]))
    if dang:
        problems.append(f"🔴 {len(dang)} dangling pointer(s): " + ", ".join(dang[:10]))
    return problems


# ── main ──────────────────────────────────────────────────────────────────────────────────────────
GENERATED_MARK = "GENERATED by `scripts/build_memory_index.py`"


def unmigrated(mem, entries):
    """A hand-written index over a store that carries no labels is NOT ours to overwrite.
    ⛔ Learned 2026-09-12 the hard way: the Stop hook fired the build on the live store BEFORE the
    migration had run, defaulted 630 files to an Unfiled tier-2 line, and overwrote both hand-written
    index files. Refuse when MEMORY.md exists without the generated marker and most files carry no label."""
    p = os.path.join(mem, INDEX_T1)
    if not os.path.exists(p) or not entries:
        return False
    if GENERATED_MARK in open(p, encoding="utf-8", errors="ignore").read():
        return False
    unlabeled = sum(1 for e in entries if e.section == UNFILED)
    return unlabeled > len(entries) / 2


def build(mem, demote=True, write=True, quiet=False):
    entries, orphans = load_entries(mem)
    if unmigrated(mem, entries):
        msg = ("🔴 store not migrated: MEMORY.md is hand-written and most files carry no label; "
               "run scripts/migrate_memory_index.py first. Nothing written.")
        if not quiet:
            print(msg)
        return None, None, [], [msg]
    moved = []
    t1 = render(entries, 1)
    over, lines, nbytes = over_budget(t1)
    if over and demote:
        candidates = sorted((e for e in entries if e.tier == 1 and not e.pinned() and not e.lane_only),
                            key=lambda e: (e.modified, e.slug))
        while over and candidates:
            e = candidates.pop(0)
            e.tier = 2
            moved.append(e)
            t1 = render(entries, 1)
            over, lines, nbytes = over_budget(t1)
    t2 = render(entries, 2)
    lane_texts = render_lanes(entries)
    problems = verify_index(mem, t1, t2, orphans, lane_texts)
    if over:
        newest = sorted((e for e in entries if e.tier == 1 and not e.lane_only), key=lambda e: -e.modified)[:10]
        problems.append(f"🔴 MEMORY.md over budget: {nbytes:,}B/{MAX_BYTES:,} · {lines}/{MAX_LINES} lines "
                        f"(80% of the {CAP_BYTES:,}B/{CAP_LINES}-line cap); nothing left to demote. "
                        f"Newest tier-1 entries: " + ", ".join(e.slug for e in newest))
    if write:
        for e in moved:
            write_meta(e.path, {"tier": 2})
        _write_if_changed(os.path.join(mem, INDEX_T1), t1)
        _write_if_changed(os.path.join(mem, INDEX_T2), t2)
        lanes_dir = os.path.join(mem, LANE_DIR)
        os.makedirs(lanes_dir, exist_ok=True)
        for lane, lt in lane_texts.items():
            _write_if_changed(os.path.join(lanes_dir, f"{lane}.md"), lt)
    if not quiet:
        for e in moved:
            when = datetime.fromtimestamp(e.modified, timezone.utc).date()
            print(f"↓ demoted to tier 2 (oldest unmarked, {when}): {e.slug}  [{e.label[:50]}]")
        if moved:
            print(f"↓ {len(moved)} pointer(s) demoted; tier 1 now {nbytes:,}B / {lines} lines")
        for p in problems:
            print(p)
    return t1, t2, moved, problems


def _write_if_changed(path, text):
    cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if cur != text:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)


def check(mem):
    entries, orphans = load_entries(mem)
    if unmigrated(mem, entries):
        print("🔴 store not migrated: run scripts/migrate_memory_index.py first")
        return ["unmigrated"]
    t1, t2 = render(entries, 1), render(entries, 2)
    lane_texts = render_lanes(entries)
    problems = verify_index(mem, t1, t2, orphans, lane_texts)
    over, lines, nbytes = over_budget(t1)
    if over:
        cands = sorted((e for e in entries if e.tier == 1 and not e.pinned() and not e.lane_only),
                       key=lambda e: (e.modified, e.slug))
        problems.append(f"🔴 MEMORY.md would be over budget: {nbytes:,}B/{MAX_BYTES:,} · {lines}/{MAX_LINES} lines; "
                        f"a build would demote (oldest first): " + ", ".join(e.slug for e in cands[:10]))
    for name, text in ((INDEX_T1, t1), (INDEX_T2, t2)):
        p = os.path.join(mem, name)
        disk = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if disk is None:
            problems.append(f"🔴 {name} missing; run scripts/build_memory_index.py")
        elif disk != text:
            dlinks = set(POINTER_RE.findall(disk))
            dang = sorted(dlinks - {e.slug for e in entries})
            if dang:
                problems.append(f"🔴 {name} on disk has {len(dang)} dangling pointer(s): " + ", ".join(dang[:10]))
            problems.append(f"🔴 {name} on disk differs from the build (hand edit or stale); rebuild, never hand edit")
    for lane, lt in lane_texts.items():
        name = f"{LANE_DIR}/{lane}.md"
        p = os.path.join(mem, LANE_DIR, f"{lane}.md")
        disk = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if disk is None:
            problems.append(f"🔴 {name} missing; run scripts/build_memory_index.py")
        elif disk != lt:
            problems.append(f"🔴 {name} on disk differs from the build (hand edit or stale); rebuild, never hand edit")
    for p in problems:
        print(p)
    return problems


def main(argv):
    mem = store_dir()
    if not mem or not os.path.isdir(mem):
        print("⚠️ no memory store found — nothing to build (set JOBSEARCH_MEMORY_DIR)")
        return 0
    if "--check" in argv:
        return 1 if check(mem) else 0
    quiet = "--quiet" in argv
    _, _, moved, problems = build(mem, demote="--no-demote" not in argv, write=True, quiet=quiet)
    if problems:
        return 1
    if not quiet:
        t1 = open(os.path.join(mem, INDEX_T1), encoding="utf-8").read()
        lines, nbytes = loaded_size(t1)
        print(f"✅ index built: {INDEX_T1} {nbytes:,}B/{MAX_BYTES:,} · {lines}/{MAX_LINES} lines"
              f"{' · ' + str(len(moved)) + ' demoted' if moved else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
