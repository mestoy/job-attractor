#!/usr/bin/env python3
"""build_memory_index.py — generate MEMORY.md (tier 1) and MEMORY-PLAYBOOKS.md (tier 2) from the
frontmatter of every memory file. The frontmatter is the source; the two index files are BUILD
ARTIFACTS nobody edits by hand (the owner's ruling 2026-09-12, approach D of
documents/plan-memory-index-2026-09-12.md).

Why: the harness loads only the first 200 lines / 25KB of MEMORY.md and drops the rest silently, and
the orphan rule (consistency-check.sh step 2) makes every memory file cost one pointer. Two writers on
one capped file failed: on 2026-09-12 tier 1 sat at 98% of cap with headroom for three pointers.

Each memory file carries, under `metadata:` in its frontmatter:
  tier: 1|2         1 = auto-loaded MEMORY.md, 2 = on-demand MEMORY-PLAYBOOKS.md. New files default to 2.
  label: "..."      his words, the text inside [...] of the pointer
  section: "..."    the index section heading the pointer sits under ("top" = before any heading)
  row: "..."        the bold head of the line the pointer shares ("" = a headless line)
  mark: "..."       the emoji/text glued to the front of the pointer (⛔, ⭐, 📧, "superseded:" ...)
  order: N          sort key inside the row
  lane: "..."       search|app|design|gig|all (default all) -- which lane digest an ⭐ entry lands in
                    (the owner's ruling 2026-09-13, documents/plan-memory-index-shape-2026-09-13.md)

ALWAYS tier 1, never demoted by this script: a file whose `type: user`, or whose mark or row carries
⛔. When tier 1 exceeds 80% of either cap (160 lines, 20,480 B) the build demotes the OLDEST
unmarked tier-1 pointers (frontmatter `modified`, else file mtime) to tier 2, writes `tier: 2` into
their frontmatter, and prints each move. If only marked pointers remain and tier 1 is still over,
the build fails red and names the newest tier-1 entries.

THREE OUTPUTS (2026-09-13, shape plan): MEMORY.md (tier 1, hard rules only: `type: user` and ⛔),
MEMORY-PLAYBOOKS.md (tier 2, on demand), and MEMORY-LANES/<lane>.md -- one file per lane
(search|app|design|gig|all) holding every ⭐ entry whose `lane:` matches (an `all`-lane entry lands
in every named lane's file plus its own `all.md`). ⭐ entries are NOT written into tier 1 or tier 2;
they live only in their lane digest(s), which `session_start.py` injects at sign-in by detected lane.
This is why tier 1 shrank: the marked/pinned set no longer includes ⭐, only ⛔ and `type: user`.

Usage:
  python3 scripts/build_memory_index.py            build, demote if over budget, write all outputs
  python3 scripts/build_memory_index.py --check    write nothing; red if over budget, if any on-disk
                                                   output differs from the build, or on orphans/dangling
  python3 scripts/build_memory_index.py --no-demote  build and write, but never demote; red if over
  JOBSEARCH_MEMORY_DIR=<dir> overrides the store path.
"""
